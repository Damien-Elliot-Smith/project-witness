"""Move 80: deterministic corrupted-bundle fixture generator (v02).

Builds ONE clean control plus SEVEN deliberately corrupted fixtures from
the pinned Move 71 frozen clean seed
(freeze_record/python_behaviour_freeze_v01/reference_bundle). The seed is
NEVER modified: every fixture is built in a fresh copy under the caller's
output directory.

Determinism contract:
  - no random values, no current timestamps, no environment-dependent
    content anywhere in generated bytes;
  - every mutation is a fixed byte transformation of seed bytes;
  - the path-traversal ZIP is produced by the ADOPTED deterministic
    archive builder (verify/agreement_harness_v01/corpus/build_archives),
    entry spec b"../evil" -- byte-identical to the Move 79
    TERMUX-confirmed corpus case "traversal";
  - two generations into independent fresh directories are byte-identical
    (proved by integrity_check.py and the adoption gate).

SELECTIVE checksum repair (v02, review-mandated): the adopted corpus
helper _rewrite_checksums repairs EVERY resolvable stale entry globally,
which would silently rewrite the frozen seed's pre-existing stale
bundle_checksums.txt line for case_manifest.json. Move 80 therefore uses
a fixture-local SELECTIVE dependency-closure repair that changes ONLY:
  1. the principal mutated file;
  2. checksum entries that directly declare that changed file;
  3. checksum entries that directly declare a checksum file changed by
     step 2;
  4. further enclosing declarations strictly required by that chain.
Unrelated stale entries remain byte-identical to the frozen seed. Every
repaired line is recorded (file, line number, entry, old/new digest,
reason) and pinned in the mutation ledger.

Composition: entry resolution mirrors the ADOPTED corpus semantics
(entries resolve against the checksum file's directory; labelled
provenance entries whose sibling target is absent resolve to
coordinator_output/sentinel_run/<rel>). The adopted _load/_dump JSON
byte form, the frozen Move 71 _flip_byte/EVIDENCE, the adopted archive
builder, and the adopted companion canonical writer are imported
read-only and are byte-identical to the Move 79 v27 baseline.

This module only produces bytes. Expectations live separately in
expected_results.json.
"""

