# ---------------------------------------------------------------------------
# Named tree-hash algorithms. Two DISTINCT normalizations exist and are
# never interchangeable (review-mandated naming):
#
#   seed_tree_hash_v0  -- the APPROVED contract-inventory pin algorithm:
#       files only; for each file in sorted(os.walk) order with sorted
#       names: relpath bytes, NUL, raw file bytes, NUL. Seed value pinned
#       as SEED_TREE_HASH_V0.
#
#   entry_tree_hash_v1 -- the fixture-identity algorithm: sorted entries
#       of relpath NUL type(F|D) NUL sha256(file bytes; empty for
#       directories) NUL. Includes directory entries; permission bits
#       deliberately excluded (checked against the seed by the
#       undeclared-mutation comparison instead).
# ---------------------------------------------------------------------------

SEED_TREE_HASH_V0 = (
    "70e6e975b3d5fab8d4a513573ef4d0d12ea0ca697ad287d46ea11b789abe7a24")
SEED_ENTRY_TREE_HASH_V1 = (
    "3a7ad566696155cd86a4ebe707927715495253eee4b404041eb5d4bc8cfcbb19")


def seed_tree_hash_v0(root):
    """APPROVED inventory algorithm. Byte-exact reimplementation of the
    Phase 1 inventory computation that produced the approved 70e6... pin."""
    digest = hashlib.sha256()
    for dirpath, dirnames, filenames in sorted(os.walk(root)):
        dirnames.sort()
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, root)
            digest.update(rel.encode())
            digest.update(b"\0")
            with open(full, "rb") as handle:
                digest.update(handle.read())
            digest.update(b"\0")
    return digest.hexdigest()


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def entry_tree_hash_v1(root):
    """Fixture-identity algorithm (directories + per-file SHA-256;
    permissions excluded from the pin, checked separately vs the seed)."""
    digest = hashlib.sha256()
    entries = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        for name in sorted(dirnames):
            rel = os.path.relpath(os.path.join(dirpath, name), root)
            entries.append((rel.replace(os.sep, "/"), "D", ""))
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, root)
            entries.append((rel.replace(os.sep, "/"), "F", sha256_file(full)))
    for rel, kind, content in sorted(entries):
        digest.update(rel.encode("utf-8"))
        digest.update(b"\x00")
        digest.update(kind.encode("ascii"))
        digest.update(b"\x00")
        digest.update(content.encode("ascii"))
        digest.update(b"\x00")
    return digest.hexdigest()


def fixture_filename(fixture_id):
    stem = fixture_id.lower().replace("-", "_")
    if fixture_id == "M80-PATH-TRAVERSAL-001":
        return stem + ".zip"
    return stem


def _copy_seed(dest):
    shutil.copytree(SEED, dest)


def _report_path(bundle):
    return os.path.join(bundle, "companion_report.json")


# ---------------------------------------------------------------------------
# Selective dependency-closure checksum repair (v02).
# ---------------------------------------------------------------------------

def _iter_checksum_files(bundle):
    for dirpath, _dirnames, filenames in os.walk(bundle):
        for name in sorted(filenames):
            if name.endswith("checksums.txt"):
                yield os.path.join(dirpath, name)


def _resolve_entry_target(bundle, sums_path, rel, label):
    """Mirror the ADOPTED corpus resolution semantics exactly: entries
    resolve against the checksum file's own directory; labelled
    provenance entries whose sibling target is absent resolve to
    coordinator_output/sentinel_run/<rel>."""
    base = os.path.dirname(sums_path)
    target = os.path.join(base, rel)
    if not os.path.isfile(target) and label:
        src = os.path.join(bundle, "coordinator_output",
                           "sentinel_run", rel)
        if os.path.isfile(src):
            target = src
    return target


def _bundle_rel(bundle, path):
    return os.path.relpath(path, bundle).replace(os.sep, "/")


def selective_repair(bundle, principal_changed):
    """Repair ONLY checksum entries whose resolved target lies inside the
    dependency closure of principal_changed (bundle-relative paths).
    Iterates because repairing a checksum file changes it, so entries
    that directly declare THAT file join the closure. Entries whose
    targets are outside the closure -- including the frozen seed's
    pre-existing stale case_manifest.json line -- are left byte-identical.

    Returns (changed_set, repairs) where repairs is a list of dicts:
    checksum_file, line_no, entry_rel, label, old_sha256, new_sha256,
    reason.
    """
    changed = set(principal_changed)
    repairs = []
    for _ in range(10):
        pass_changed = False
        for sums_path in _iter_checksum_files(bundle):
            sums_rel = _bundle_rel(bundle, sums_path)
            with open(sums_path, "r", encoding="utf-8") as handle:
                lines = handle.read().splitlines()
            out = []
            file_changed = False
            for line_no, line in enumerate(lines, 1):
                if not line.strip():
                    out.append(line)
                    continue
                parts = line.split("  ")
                if len(parts) == 2:
                    digest, rel = parts
                    label = None
                elif len(parts) == 3:
                    label, digest, rel = parts
                else:
                    out.append(line)
                    continue
                target = _resolve_entry_target(bundle, sums_path, rel,
                                               label)
                if not os.path.isfile(target):
                    out.append(line)
                    continue
                target_rel = _bundle_rel(bundle, target)
                if target_rel not in changed:
                    out.append(line)
                    continue
                new = sha256_file(target)
                if new == digest:
                    out.append(line)
                    continue
                repairs.append({
                    "checksum_file": sums_rel,
                    "line_no": line_no,
                    "entry_rel": rel,
                    "label": label,
                    "old_sha256": digest,
                    "new_sha256": new,
                    "reason": "declares changed file %s" % target_rel,
                })
                out.append("%s  %s  %s" % (label, new, rel)
                           if label else "%s  %s" % (new, rel))
                file_changed = True
            if file_changed:
                with open(sums_path, "w", encoding="utf-8") as handle:
                    handle.write("\n".join(out) + "\n")
                changed.add(sums_rel)
                pass_changed = True
        if not pass_changed:
            repairs.sort(key=lambda r: (r["checksum_file"], r["line_no"]))
            return changed, repairs
    raise RuntimeError("selective repair did not reach a fixpoint")


