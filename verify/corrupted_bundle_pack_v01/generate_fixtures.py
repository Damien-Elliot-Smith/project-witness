def build_traversal_zip(dest_path):
    """M80-PATH-TRAVERSAL-001: single-entry ZIP whose entry name is
    b"../evil", produced by the adopted deterministic archive builder
    (_one), byte-identical to the Move 79 corpus case "traversal"."""
    data = build_archives._one(b"../evil")
    with open(dest_path, "wb") as handle:
        handle.write(data)


def generate(out_dir):
    """Generate all eight fixtures into out_dir. Returns a dict
    fixture_id -> {"path", "kind", "hash", "checksum_line_repairs"}."""
    os.makedirs(out_dir, exist_ok=True)
    results = {}
    for fixture_id in FIXTURE_IDS:
        name = fixture_filename(fixture_id)
        target = os.path.join(out_dir, name)
        if os.path.exists(target):
            raise RuntimeError("fixture target already exists: %s" % target)
        if fixture_id == "M80-PATH-TRAVERSAL-001":
            build_traversal_zip(target)
            results[fixture_id] = {
                "path": target,
                "kind": "zip",
                "hash": sha256_file(target),
                "checksum_line_repairs": [],
            }
            continue
        _copy_seed(target)
        principal, needs_repair = BUNDLE_BUILDERS[fixture_id](target)
        repairs = []
        if needs_repair:
            _changed, repairs = selective_repair(target, principal)
        results[fixture_id] = {
            "path": target,
            "kind": "dir",
            "hash": entry_tree_hash_v1(target),
            "checksum_line_repairs": repairs,
        }
    return results


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Deterministically generate the Move 80 corrupted "
                    "bundle fixtures from the pinned frozen seed.")
    parser.add_argument("--out", required=True,
                        help="output directory (fresh; fixtures must not "
                             "already exist inside it)")
    args = parser.parse_args(argv)
    results = generate(args.out)
    for fixture_id in FIXTURE_IDS:
        info = results[fixture_id]
        print("%s  %s  %s  repairs=%d"
              % (info["hash"], fixture_id, info["kind"],
                 len(info["checksum_line_repairs"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
