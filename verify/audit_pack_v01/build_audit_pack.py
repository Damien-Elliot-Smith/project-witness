#!/usr/bin/env python3
"""Move 85 — Rust audit pack v1.

Builds the audit pack the roadmap asks for: clean, tampered and corrupted
bundles with the Python lane's captured outputs, the Rust lane's captured
outputs, instructions and known limits.

**The pack is a gate-generated PUBLICATION artifact**, written into
`MOVE85_OUTPUT_DIR`. It is deliberately not packaged in the candidate
source archive: a pack committed as source would be a claim, whereas a
pack generated by a gate run from freshly built binaries is a measurement.

Published structure, a deterministic directory tree:

    <MOVE85_OUTPUT_DIR>/audit_pack_v1/
        MANIFEST.json            index, hashes, per-case measurements
        INSTRUCTIONS.md          how to reproduce every measurement
        KNOWN_LIMITS.md          what the pack does and does not establish
        SHA256SUMS               one line per published file
        bundles/<case_id>/       the exact tree each case was measured over
        observed/<case_id>/rust.stdout   captured bytes, verbatim
        observed/<case_id>/rust.meta     exit code and stderr byte count
        observed/<case_id>/python.stdout
        observed/<case_id>/python.meta

Everything under `observed/` is an AUTHORITATIVE MEASUREMENT: the exact
bytes a real execution produced. `INSTRUCTIONS.md` and `KNOWN_LIMITS.md`
are EXPLANATORY TEXT and are labelled as such in the manifest.

**Determinism boundary.** `MANIFEST.json` and the two documents regenerate
byte-for-byte from the same inputs. To make that true the manifest carries
no timestamp, no temporary absolute path, no random name, no run-directory
identity and no host-specific value; paths are relative to the pack root
and every list is explicitly sorted. This determinism claim is about the
pack REPRESENTATION only. It is **not** a claim that Rust binaries or
builds are reproducible; nothing here measures that.

Nothing is published until every substantive check has passed: the pack is
assembled in a private staging directory and moved into place only at the
end, and any check failure aborts before publication.
"""

import argparse
import hashlib
import json
import os
import shutil
import stat
import subprocess
import sys

RUN_TIMEOUT_SECONDS = 300
PACK_DIRNAME = "audit_pack_v1"

# Case ids. The three demonstration cases come from the adopted Move 84
# fixture builder; the corrupted cases come from the adopted Move 80 pack.
DEMO_CASES = ("clean", "toplevel_tamper", "nested_evidence_tamper")


class AuditPackError(Exception):
    """Deterministic, message-only failure."""


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        while True:
            chunk = handle.read(1024 * 1024)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


def run_capture(argv):
    proc = subprocess.run(argv, capture_output=True,
                          timeout=RUN_TIMEOUT_SECONDS)
    return proc.returncode, proc.stdout, proc.stderr


def verdict_of(stdout_bytes):
    """Read the verdict out of a real Rust line, without predicting it."""
    text = stdout_bytes.decode("utf-8", "replace")
    try:
        return json.loads(text.strip()).get("verdict")
    except ValueError:
        pass
    for part in text.split(","):
        if "verdict" in part:
            return part.split(":", 1)[-1].strip().strip('" ')
    return None


def reason_of(stdout_bytes):
    text = stdout_bytes.decode("utf-8", "replace")
    try:
        return json.loads(text.strip()).get("reason_code")
    except ValueError:
        pass
    for part in text.split(","):
        if "reason_code" in part:
            return part.split(":", 1)[-1].strip().strip('" ')
    return None


def measure(case_id, root, rust_bin, python_bin, companion):
    """Execute BOTH lanes over one case and record exactly what happened."""
    r_rc, r_out, r_err = run_capture([rust_bin, "verify", root])
    p_rc, p_out, p_err = run_capture(
        [python_bin, "-B", companion, "verify", "--run", root])
    return {
        "case_id": case_id,
        "rust": {"exit_code": r_rc, "stdout_sha256": sha256_bytes(r_out),
                 "stderr_bytes": len(r_err),
                 "verdict": verdict_of(r_out),
                 "reason_code": reason_of(r_out)},
        "python": {"exit_code": p_rc, "stdout_sha256": sha256_bytes(p_out),
                   "stderr_bytes": len(p_err)},
        "_raw": {"rust_stdout": r_out, "python_stdout": p_out},
    }


def check_measurements(measurements, divergence_ids):
    """Invariants derived from the adopted contract, checked against real
    measurements. Failing any of these aborts before publication."""
    problems = []
    by_id = {m["case_id"]: m for m in measurements}

    # no Rust PASS was observed on any measured surface
    for m in measurements:
        if m["rust"]["verdict"] == "PASS" or m["rust"]["exit_code"] == 0:
            problems.append(
                "%s: a Rust PASS was observed; the adopted verifier "
                "declares no PASS-producing path" % m["case_id"])
        if m["rust"]["stderr_bytes"] or m["python"]["stderr_bytes"]:
            problems.append("%s: a lane emitted stderr" % m["case_id"])

    for required in DEMO_CASES:
        if required not in by_id:
            problems.append("missing demonstration case: %s" % required)
    if problems:
        return problems

    clean = by_id["clean"]
    top = by_id["toplevel_tamper"]
    nested = by_id["nested_evidence_tamper"]

    if clean["rust"]["verdict"] != "INCONCLUSIVE" or \
            clean["rust"]["exit_code"] != 3:
        problems.append("clean: Rust is not INCONCLUSIVE/3")
    if clean["python"]["exit_code"] != 0:
        problems.append("clean: the Python lane did not accept the bundle")
    if top["rust"]["verdict"] != "FAIL" or top["rust"]["exit_code"] != 1:
        problems.append(
            "toplevel_tamper: the Rust lane did not detect the tamper")
    # the limitation must be OBSERVED, not assumed
    if nested["rust"]["stdout_sha256"] != clean["rust"]["stdout_sha256"]:
        problems.append(
            "nested_evidence_tamper: the Rust output differs from clean, "
            "so the documented blindness was not observed")
    if nested["python"]["exit_code"] == 0:
        problems.append(
            "nested_evidence_tamper: the Python lane failed to detect it")
    if not divergence_ids:
        problems.append("no adopted divergence IDs were supplied")
    return problems


def render_instructions(cases):
    lines = [
        "# Project Witness — Rust audit pack v1: instructions",
        "",
        "This pack is EXPLANATORY TEXT plus AUTHORITATIVE MEASUREMENTS.",
        "Everything under `observed/` is the exact bytes a real execution",
        "produced. This document and `KNOWN_LIMITS.md` are explanation.",
        "",
        "## Reproducing a measurement",
        "",
        "For each case below, `bundles/<case_id>/` is the exact tree that",
        "was measured. Build the verifier from the adopted source, then:",
        "",
        "    witness-verify verify bundles/<case_id>",
        "    python3 src/12_companion_cli_v031/companion.py verify \\",
        "        --run bundles/<case_id>",
        "",
        "Compare the SHA-256 of each stdout against the value recorded in",
        "`MANIFEST.json`, and the exit codes against the same record.",
        "",
        "## Cases",
        "",
    ]
    for case_id in sorted(cases):
        lines.append("- `%s`" % case_id)
    lines.append("")
    lines.append("## Verifying this pack")
    lines.append("")
    lines.append("`SHA256SUMS` lists every published file. Recompute and")
    lines.append("compare. `MANIFEST.json` records, per case, the exit")
    lines.append("codes, the stdout hashes and the verdict and reason code")
    lines.append("READ FROM the real output rather than predicted.")
    lines.append("")
    return "\n".join(lines) + "\n"


def render_known_limits(divergence_ids):
    lines = [
        "# Project Witness — Rust audit pack v1: known limits",
        "",
        "## What this pack establishes",
        "",
        "It records what the adopted verifiers did on the measured cases,",
        "on the platform the measurements were taken on.",
        "",
        "## What it does NOT establish",
        "",
        "- It does not establish that no reachable PASS-producing path",
        "  exists in the Rust verifier. The adopted source declares only",
        "  the verdict constants FAIL and INCONCLUSIVE and states the",
        "  honesty property in its own header; finite execution shows only",
        "  that no PASS was OBSERVED on the measured surfaces.",
        "- INCONCLUSIVE is not PASS. It is the adopted verifier's honest",
        "  ceiling for a clean bundle.",
        "- The Rust verifier does NOT detect a tamper to the nested",
        "  evidence payload. Its output for that case is byte-identical to",
        "  the clean case. The Python lane does detect it.",
        "- Python and Rust are NOT behaviourally equivalent. Two adopted",
        "  divergences remain, and they are preserved deliberately:",
        "",
    ]
    for div in sorted(divergence_ids):
        lines.append("      %s" % div)
    lines += [
        "",
        "- Only Android/Termux AArch64 has been build- and runtime-tested.",
        "  Linux x86_64, Linux AArch64 and Windows x86_64 are",
        "  UNESTABLISHED. An Android/Termux AArch64 binary is not a",
        "  generic Linux AArch64 binary.",
        "- Build provenance records measured facts about ONE build. It",
        "  does not establish reproducible builds.",
        "- This pack's own representation regenerates byte-for-byte from",
        "  the same inputs. That is a property of the pack, NOT of any",
        "  binary or build.",
        "- Recording a historical fact here does not establish it. The",
        "  adopted gates establish; this pack reports.",
        "",
    ]
    return "\n".join(lines) + "\n"


def build(args):
    staging = os.path.join(args.staging, PACK_DIRNAME)
    if os.path.isdir(staging):
        shutil.rmtree(staging)
    os.makedirs(staging)

    with open(args.fixtures, encoding="utf-8") as handle:
        fixture_cases = json.load(handle)["cases"]
    divergence_ids = sorted(args.divergence_id or [])

    measurements = []
    for case in fixture_cases:
        case_id = case["case_id"]
        root = case["root"]
        record = measure(case_id, root, args.verifier, args.python_bin,
                         args.companion)
        measurements.append(record)

    problems = check_measurements(measurements, divergence_ids)
    if problems:
        for problem in sorted(set(problems)):
            print("AUDIT_PACK_PROBLEM: %s" % problem)
        raise AuditPackError("%d measurement problem(s)" % len(set(problems)))

    # ---- assemble, in a private staging directory ----
    for case in fixture_cases:
        dest = os.path.join(staging, "bundles", case["case_id"])
        shutil.copytree(case["root"], dest, symlinks=True)
    for record in measurements:
        obs = os.path.join(staging, "observed", record["case_id"])
        os.makedirs(obs)
        with open(os.path.join(obs, "rust.stdout"), "wb") as handle:
            handle.write(record["_raw"]["rust_stdout"])
        with open(os.path.join(obs, "python.stdout"), "wb") as handle:
            handle.write(record["_raw"]["python_stdout"])
        for lane in ("rust", "python"):
            meta = {"exit_code": record[lane]["exit_code"],
                    "stderr_bytes": record[lane]["stderr_bytes"]}
            with open(os.path.join(obs, "%s.meta" % lane), "wb") as handle:
                handle.write((json.dumps(meta, sort_keys=True,
                                         separators=(",", ":"))
                              + "\n").encode("utf-8"))

    cases_out = []
    for record in sorted(measurements, key=lambda r: r["case_id"]):
        stripped = {k: v for k, v in record.items() if k != "_raw"}
        cases_out.append(stripped)

    manifest = {
        "schema_version": "witness-audit-pack/1",
        "pack_name": PACK_DIRNAME,
        "cases": cases_out,
        "adopted_divergence_ids": divergence_ids,
        "authoritative_measurements": ["observed/"],
        "explanatory_text": ["INSTRUCTIONS.md", "KNOWN_LIMITS.md"],
        "determinism_scope": (
            "This manifest and the two documents regenerate byte-for-byte "
            "from the same inputs. That is a property of this pack's "
            "representation only and is NOT a claim that Rust binaries or "
            "builds are reproducible."),
        "not_established": [
            "no reachable PASS path (only: no PASS observed on the "
            "measured surfaces)",
            "Linux x86_64 runtime",
            "Linux AArch64 runtime",
            "Windows x86_64 runtime",
            "reproducible builds",
        ],
    }
    with open(os.path.join(staging, "MANIFEST.json"), "wb") as handle:
        handle.write((json.dumps(manifest, sort_keys=True, indent=1,
                                 ensure_ascii=False) + "\n")
                     .encode("utf-8"))
    with open(os.path.join(staging, "INSTRUCTIONS.md"), "wb") as handle:
        handle.write(render_instructions(
            [m["case_id"] for m in measurements]).encode("utf-8"))
    with open(os.path.join(staging, "KNOWN_LIMITS.md"), "wb") as handle:
        handle.write(render_known_limits(divergence_ids).encode("utf-8"))

    sums = []
    for dirpath, dirnames, filenames in os.walk(staging):
        dirnames.sort()
        for name in sorted(filenames):
            if name == "SHA256SUMS":
                continue
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, staging).replace(os.sep, "/")
            sums.append("%s  %s" % (sha256_file(full), rel))
    sums.sort(key=lambda line: line.split("  ", 1)[1])
    with open(os.path.join(staging, "SHA256SUMS"), "wb") as handle:
        handle.write(("\n".join(sums) + "\n").encode("utf-8"))

    print("AUDIT_PACK_CASES: %d" % len(measurements))
    for record in cases_out:
        print("AUDIT_PACK_CASE: %-24s rust %s/%s exit %d | python exit %d"
              % (record["case_id"], record["rust"]["verdict"],
                 record["rust"]["reason_code"], record["rust"]["exit_code"],
                 record["python"]["exit_code"]))
    print("AUDIT_PACK_DIVERGENCE_IDS: %s" % " ".join(divergence_ids))
    print("AUDIT_PACK_FILES: %d" % len(sums))
    return staging


def publish_verified(source_pack, publish_root):
    """Publish an ALREADY-VERIFIED staged pack, without regenerating it.

    The Move 85 roadmap deliverable is the audit pack. The gate builds and
    verifies it in private staging; this copies that exact verified
    representation into the publication directory and then INDEPENDENTLY
    verifies the published tree against the staged source. Nothing is
    regenerated here: regenerating during publication would publish an
    artifact that no check had passed.

    Fail-closed. If verification fails after copying, the partial
    publication is rolled back and the failure is reported.
    """
    problems = []
    if not os.path.isdir(source_pack):
        raise AuditPackError("staged pack not found: %s" % source_pack)
    dest = os.path.join(publish_root, PACK_DIRNAME)
    if os.path.exists(dest):
        raise AuditPackError(
            "publication target already exists: %s" % dest)

    def _tree(root):
        """relpath -> (kind, mode, sha256 or link target)."""
        found = {}
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames.sort()
            for name in sorted(dirnames) + sorted(filenames):
                full = os.path.join(dirpath, name)
                rel = os.path.relpath(full, root).replace(os.sep, "/")
                info = os.lstat(full)
                mode = stat.S_IMODE(info.st_mode)
                if stat.S_ISLNK(info.st_mode):
                    found[rel] = ("symlink", mode, os.readlink(full))
                elif stat.S_ISDIR(info.st_mode):
                    found[rel] = ("dir", mode, "")
                elif stat.S_ISREG(info.st_mode):
                    found[rel] = ("file", mode, sha256_file(full))
                else:
                    found[rel] = ("other", mode, "")
        return found

    before = _tree(source_pack)
    try:
        shutil.copytree(source_pack, dest, symlinks=True)
    except OSError as exc:
        shutil.rmtree(dest, ignore_errors=True)
        raise AuditPackError("copy failed and was rolled back: %s" % exc)

    after = _tree(dest)
    if set(before) != set(after):
        missing = sorted(set(before) - set(after))
        extra = sorted(set(after) - set(before))
        problems.append("published tree differs: missing=%s extra=%s"
                        % (missing[:5], extra[:5]))
    else:
        for rel in sorted(before):
            if before[rel] != after[rel]:
                problems.append("published entry differs: %s" % rel)

    # SHA256SUMS is recomputed from the PUBLISHED bytes
    sums_path = os.path.join(dest, "SHA256SUMS")
    if not os.path.isfile(sums_path):
        problems.append("published pack has no SHA256SUMS")
    else:
        listed = {}
        with open(sums_path, encoding="utf-8") as handle:
            for line in handle:
                line = line.rstrip("\n")
                if not line:
                    continue
                digest, rel = line.split("  ", 1)
                listed[rel] = digest
        published = {rel: info[2] for rel, info in after.items()
                     if info[0] == "file" and rel != "SHA256SUMS"}
        if set(listed) != set(published):
            problems.append(
                "published SHA256SUMS does not cover the published pack")
        else:
            for rel, digest in sorted(listed.items()):
                if published[rel] != digest:
                    problems.append(
                        "published byte mismatch against SHA256SUMS: %s"
                        % rel)

    if problems:
        shutil.rmtree(dest, ignore_errors=True)
        for problem in sorted(set(problems)):
            print("AUDIT_PACK_PUBLISH_PROBLEM: %s" % problem)
        raise AuditPackError(
            "publication verification failed and was rolled back "
            "(%d problem(s))" % len(set(problems)))

    print("AUDIT_PACK_PUBLISHED_ENTRIES: %d" % len(after))
    print("AUDIT_PACK_PUBLISHED_VERIFIED: %s" % PACK_DIRNAME)
    return dest


def main(argv=None):
    parser = argparse.ArgumentParser(description="Move 85 audit pack v1")
    parser.add_argument("--publish-verified-from", default=None,
                        help="absolute path to an ALREADY-VERIFIED staged "
                             "audit_pack_v1 directory; with --publish-to, "
                             "publishes it without regenerating anything")
    parser.add_argument("--verifier", required=False)
    parser.add_argument("--python-bin", required=False)
    parser.add_argument("--companion", required=False)
    parser.add_argument("--fixtures", required=False)
    parser.add_argument("--staging", required=False)
    parser.add_argument("--divergence-id", action="append", default=[])
    parser.add_argument("--publish-to", default=None,
                        help="absolute directory; publication happens only "
                             "after every check has passed")
    args = parser.parse_args(argv)

    # ---- publication-only mode ----
    if args.publish_verified_from:
        if not args.publish_to:
            print("usage error: --publish-verified-from requires "
                  "--publish-to")
            return 2
        for label, path in (("--publish-verified-from",
                             args.publish_verified_from),
                            ("--publish-to", args.publish_to)):
            if not os.path.isabs(path) or not os.path.exists(path):
                print("usage error: %s must be an absolute existing path"
                      % label)
                return 2
        try:
            publish_verified(args.publish_verified_from, args.publish_to)
        except (AuditPackError, OSError) as exc:
            print("MOVE_85_AUDIT_PACK_PUBLICATION: FAIL (%s)" % exc)
            return 1
        print("MOVE_85_AUDIT_PACK_PUBLICATION: PASS")
        return 0

    for label, value in (("--verifier", args.verifier),
                         ("--python-bin", args.python_bin),
                         ("--companion", args.companion),
                         ("--fixtures", args.fixtures),
                         ("--staging", args.staging)):
        if not value:
            print("usage error: %s is required for pack construction"
                  % label)
            return 2

    for label, path in (("--verifier", args.verifier),
                        ("--python-bin", args.python_bin),
                        ("--companion", args.companion),
                        ("--fixtures", args.fixtures),
                        ("--staging", args.staging)):
        if not os.path.isabs(path) or not os.path.exists(path):
            print("usage error: %s must be an absolute existing path"
                  % label)
            return 2
    if args.publish_to and not os.path.isabs(args.publish_to):
        print("usage error: --publish-to must be absolute")
        return 2

    try:
        staging = build(args)
    except (AuditPackError, OSError, ValueError, KeyError) as exc:
        print("MOVE_85_AUDIT_PACK: FAIL (%s)" % exc)
        return 1

    if args.publish_to:
        dest = os.path.join(args.publish_to, PACK_DIRNAME)
        if os.path.exists(dest):
            print("MOVE_85_AUDIT_PACK: FAIL (publication target exists)")
            return 1
        shutil.copytree(staging, dest, symlinks=True)
        print("AUDIT_PACK_PUBLISHED: %s" % PACK_DIRNAME)
    print("MOVE_85_AUDIT_PACK: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
